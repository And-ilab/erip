def sentence_count(text: str) -> int:
    return text.count(". ") + (1 if text.endswith(".") else 0)


def by_name(rows: list[tuple]) -> dict[str, str]:
    found: dict[str, str] = {}
    for name, code, description, result, prompt in rows:
        description = scrub(description)
        result = scrub(result)
        prompt = scrub(prompt)
        count = sentence_count(description)
        if count != 6:
            raise SystemExit(f"{code} sentences={count}")
        if name in found:
            raise SystemExit(f"duplicate name {name}")
        found[name] = body(code, description, result, prompt)
    return found


def fresh(rows: list[tuple[str, str, list[str], str, str]]) -> dict[str, str]:
    packed = [(name, code, pack(sentences), result, prompt) for name, code, sentences, result, prompt in rows]
    return by_name(packed)


def task_names(start: int, end: int) -> dict[int, str]:
    book = openpyxl.load_workbook(SOURCE, read_only=True, data_only=True)
    names: dict[int, str] = {}
    for row in book.active.iter_rows(min_row=2, values_only=True):
        if not row or row[0] in (None, ""):
            continue
        number = int(row[0])
        if start <= number <= end:
            names[number] = str(row[2])
    book.close()
    if set(names) != set(range(start, end + 1)):
        missing = sorted(set(range(start, end + 1)) - set(names))
        raise SystemExit(f"missing tasks {missing}")
    return names


def write_book(path: Path, title: str, start: int, end: int, names: dict[int, str], texts: dict[str, str]) -> None:
    book = openpyxl.Workbook()
    sheet = book.active
    sheet.title = title
    sheet.append(["Номер", "Описание"])
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")
    codes: list[str] = []
    for number in range(start, end + 1):
        name = names[number]
        if name not in texts:
            raise SystemExit(f"no description for {number} {name}")
        text = texts[name]
        if "readme" in text.lower():
            raise SystemExit(f"readme in {number}")
        codes.append(text.split("\n", 1)[0])
        sheet.append([number, text])
        sheet.cell(sheet.max_row, 1).alignment = Alignment(vertical="top")
        sheet.cell(sheet.max_row, 2).alignment = wrap
    if len(set(codes)) != end - start + 1:
        raise SystemExit(f"{path.name} ids {len(set(codes))}")
    sheet.column_dimensions["A"].width = 12
    sheet.column_dimensions["B"].width = 110
    sheet.freeze_panes = "A2"
    book.save(path)
    print(f"{path.name} {sheet.max_row - 1}")


