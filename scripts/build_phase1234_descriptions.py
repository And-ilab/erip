def pack(sentences: list[str]) -> str:
    if len(sentences) != 6:
        raise SystemExit(f"need 6, got {len(sentences)}: {sentences[0][:40]}")
    for sentence in sentences:
        if ". " in sentence or not sentence.endswith("."):
            raise SystemExit(f"bad sentence: {sentence}")
    return " ".join(sentences)


