    hdr = table.rows[0]
    format_cell(hdr.cells[0], headers[0], bold=True, size=11, shading=GREY_FILL, color=RGBColor(0xFF,0xFF,0xFF))
    format_cell(hdr.cells[1], headers[1], bold=True, size=11, shading=GREY_FILL, color=RGBColor(0xFF,0xFF,0xFF))
    set_repeat_header(hdr)
    for a, b in rows:
        row = table.add_row()
        format_cell(row.cells[0], a, bold=True, size=11)
        format_cell(row.cells[1], b, size=11)
    set_col_widths(table, widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return table

