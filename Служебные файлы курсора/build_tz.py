def multi_col_table(headers, rows, widths, header_shading=GREY_FILL, font_size=10):
    n = len(headers)
    table = doc.add_table(rows=1, cols=n)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(table)
    hdr = table.rows[0]
    for i, htext in enumerate(headers):
        format_cell(hdr.cells[i], htext, bold=True, size=font_size + 1, shading=header_shading, color=RGBColor(0xFF,0xFF,0xFF),
                    align=WD_ALIGN_PARAGRAPH.CENTER)
    set_repeat_header(hdr)
    for r in rows:
        row = table.add_row()
        for i, val in enumerate(r):
            bold = (i == 0)
            format_cell(row.cells[i], val, bold=bold, size=font_size)
    set_col_widths(table, widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return table

