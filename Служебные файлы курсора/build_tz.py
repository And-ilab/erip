def set_col_widths(table, widths_cm):
    table.autofit = False
    table.allow_autofit = False
    tblPr = table._tbl.tblPr
    layout = OxmlElement('w:tblLayout')
    layout.set(qn('w:type'), 'fixed')
    tblPr.append(layout)
    for row in table.rows:
        for idx, w in enumerate(widths_cm):
            if idx < len(row.cells):
                row.cells[idx].width = Cm(w)
    grid = table._tbl.find(qn('w:tblGrid'))
    if grid is not None:
        for idx, gridCol in enumerate(grid.findall(qn('w:gridCol'))):
            if idx < len(widths_cm):
                gridCol.set(qn('w:w'), str(int(widths_cm[idx] * 567)))

def set_cell_shading(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def set_repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    th = OxmlElement('w:tblHeader')
    th.set(qn('w:val'), "true")
    trPr.append(th)

def set_table_borders(table, sz=4, color="7F9CB5"):
    tbl = table._tbl
    tblPr = tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), str(sz))
        el.set(qn('w:space'), '0')
        el.set(qn('w:color'), color)
        borders.append(el)
    tblPr.append(borders)

def format_cell(cell, text=None, bold=False, italic=False, size=11, align=WD_ALIGN_PARAGRAPH.LEFT,
                 color=None, shading=None, valign=WD_ALIGN_VERTICAL.CENTER, font=FONT_BODY):
    if shading:
        set_cell_shading(cell, shading)
    cell.vertical_alignment = valign
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for side in ('top', 'left', 'bottom', 'right'):
        node = OxmlElement(f'w:{side}')
        node.set(qn('w:w'), '80')
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)
    if text is None:
        return
    para = cell.paragraphs[0]
    para.alignment = align
    para.paragraph_format.space_after = Pt(2)
    para.paragraph_format.space_before = Pt(2)
    lines = str(text).split("\n")
    run = para.add_run(lines[0])
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.name = font
    if color:
        run.font.color.rgb = color
    for extra in lines[1:]:
        r = para.add_run()
        r.add_break()
        r2 = para.add_run(extra)
        r2.font.size = Pt(size)
        r2.font.bold = bold
        r2.font.italic = italic
        r2.font.name = font
        if color:
            r2.font.color.rgb = color

def add_landscape_section():
    """Начинает новый раздел документа в альбомной ориентации."""
    new_sec = doc.add_section(WD_SECTION.NEW_PAGE)
    new_sec.orientation = WD_ORIENT.LANDSCAPE
    w, h = new_sec.page_width, new_sec.page_height
    new_sec.page_width, new_sec.page_height = h, w
    new_sec.left_margin = Cm(1.5)
    new_sec.right_margin = Cm(1.5)
    new_sec.top_margin = Cm(1.5)
    new_sec.bottom_margin = Cm(1.5)
    return new_sec

def add_portrait_section():
    new_sec = doc.add_section(WD_SECTION.NEW_PAGE)
    new_sec.orientation = WD_ORIENT.PORTRAIT
    w, h = new_sec.page_width, new_sec.page_height
    if w > h:
        new_sec.page_width, new_sec.page_height = h, w
    new_sec.left_margin = Cm(2.5)
    new_sec.right_margin = Cm(1.5)
    new_sec.top_margin = Cm(2)
    new_sec.bottom_margin = Cm(2)
    return new_sec

