def p(text="", bold=False, italic=False, align=None, size=12, color=None, space_after=6):
    para = doc.add_paragraph()
    if align:
        para.alignment = align
    para.paragraph_format.space_after = Pt(space_after)
    run = para.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    if color:
        run.font.color.rgb = color
    return para

def p_rich(runs, align=None, space_after=6):
    """runs: list of (text, bold, italic)"""
    para = doc.add_paragraph()
    if align:
        para.alignment = align
    para.paragraph_format.space_after = Pt(space_after)
    for r in runs:
        text, bold, italic = (r + (False, False))[:3] if len(r) < 3 else r
        run = para.add_run(text)
        run.bold = bold
        run.italic = italic
    return para

def bullet(text, level=0):
    para = doc.add_paragraph(style="List Bullet")
    if level:
        para.paragraph_format.left_indent = Cm(0.9 + 0.6 * level)
    run = para.add_run(text)
    return para

def numbered(text):
    para = doc.add_paragraph(style="List Number")
    para.add_run(text)
    return para

def caption(text):
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run(text)
    run.italic = True
    run.font.size = Pt(10)
    para.paragraph_format.space_before = Pt(2)
    para.paragraph_format.space_after = Pt(10)

def field_value_table(rows, headers=("Поле", "Значение"), widths=(5.5, 10.5)):
    table = doc.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
