def roman_to_arabic_ref(roman_part: str, rest: str) -> str:
    """rest like '.5' or '.5.1' or ''."""
    if roman_part == "XII":
        key = "XII" + rest
        if key in XII_MAP:
            return XII_MAP[key]
        if rest.startswith(".5"):
            return "Приложение 3" + rest[2:]
        if rest.startswith(".1"):
            return "5" + rest[2:]
        if rest.startswith(".2"):
            return "6" + rest[2:]
        if rest.startswith(".3"):
            return "7" + rest[2:]
        if rest.startswith(".4"):
            return "8" + rest[2:]
        return "разделы 5–8"
    if roman_part == "I":
        # longest match
        full = "I" + rest
        for k in sorted(I_MAP.keys(), key=len, reverse=True):
            if full == k or full.startswith(k + ".") or full.startswith(k + " "):
                return I_MAP[k] + full[len(k) :]
        if rest == "" or rest.startswith("."):
            # I.4 etc.
            m = re.match(r"\.(\d+(?:\.\d+)*)", rest)
            if m:
                key = "I." + m.group(1)
                # try progressive
                parts = m.group(1).split(".")
                for i in range(len(parts), 0, -1):
                    k = "I." + ".".join(parts[:i])
                    if k in I_MAP:
                        return I_MAP[k]
            return "раздел 1"
        return "раздел 1"
    if roman_part in MODULE_PREFIX:
        base = MODULE_PREFIX[roman_part]
        if rest == "":
            return base
        # XI.0 → 4.2.10.1 (общие положения) — сохраняем .0 как .0 или заменим на .1
        if rest == ".0":
            return base + ".0"
        return base + rest
    return roman_part + rest


_REF_RE = re.compile(
    r"\b(XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)((?:\.\d+){1,4})\b"
)
_PART_RE = re.compile(
    r"Часть\s+(XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)\b"
)
_PARTS_RANGE_RE = re.compile(
    r"Части\s+(II|III|IV|V|VI|VII|VIII|IX|X|XI)–(II|III|IV|V|VI|VII|VIII|IX|X|XI)"
)
_HEADING_RE = re.compile(
    r"^(XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)((?:\.\d+){1,4})\.\s*"
)


def replace_numbering_in_text(text: str) -> str:
    if not text:
        return text

    def repl_parts_range(m: re.Match) -> str:
        a, b = m.group(1), m.group(2)
        return f"пп. {MODULE_PREFIX.get(a, a)}–{MODULE_PREFIX.get(b, b)}"

    text = _PARTS_RANGE_RE.sub(repl_parts_range, text)

    def repl_part(m: re.Match) -> str:
        p = m.group(1)
        return PART_NAME.get(p, m.group(0))

    text = _PART_RE.sub(repl_part, text)

    def repl_ref(m: re.Match) -> str:
        return roman_to_arabic_ref(m.group(1), m.group(2))

    text = _REF_RE.sub(repl_ref, text)
    return text


def replace_heading(text: str) -> str:
    m = _HEADING_RE.match(text)
    if not m:
        # Часть II. ...
        m2 = re.match(
            r"^Часть\s+(XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)\.\s*(.*)$", text
        )
        if m2:
            p, rest = m2.group(1), m2.group(2)
            if p in MODULE_PREFIX:
                return f"{MODULE_PREFIX[p]}. {rest}"
            if p == "XII":
                return f"5–8. {rest}" if rest else "Разделы 5–8"
            if p == "I":
                return f"1. {rest}" if rest else "1. Общие сведения"
        return replace_numbering_in_text(text)
    new_num = roman_to_arabic_ref(m.group(1), m.group(2))
    rest = text[m.end() :]
    # I.6. Title → 4.1.1. Title
    if m.group(1) == "I":
        mapping_titles = {
            "I.6": "4.1.1",
            "I.8": "3.1",
            "I.9": "Приложение 2",
            "I.10": "4.4.4",
            "I.11": "4.4.4",
            "I.12": "4.4.8",
            "I.13": "4.4.6",
        }
        full = m.group(1) + m.group(2)
        for k, v in mapping_titles.items():
            if full == k:
                new_num = v
                break
    return f"{new_num}. {rest}" if rest else f"{new_num}."


