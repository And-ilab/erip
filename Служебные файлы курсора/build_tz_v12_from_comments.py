def apply_text_node_replacements(root: ET.Element) -> int:
    count = 0
    for t in root.iter(W + "t"):
        if not t.text:
            continue
        original = t.text
        new = original
        for old, repl in LITERAL_REPLACEMENTS:
            if old in new:
                new = new.replace(old, repl)
        new2 = replace_numbering_in_text(new)
        # headings inside single text node
        if _HEADING_RE.match(new2.strip()) or new2.strip().startswith("Часть "):
            stripped = new2.strip()
            # only if paragraph is essentially a heading — handled separately
            pass
        if new2 != original:
            t.text = new2
            if new2.startswith(" ") or new2.endswith(" ") or "  " in new2:
                t.set(XML_SPACE, "preserve")
            count += 1
    return count


def apply_heading_paragraphs(root: ET.Element) -> int:
    count = 0
    for p in root.iter(W + "p"):
        full = paragraph_full_text(p).strip()
        if not full:
            continue
        if _HEADING_RE.match(full) or re.match(
            r"^Часть\s+(XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)\.", full
        ):
            new_full = replace_heading(full)
            if new_full != full:
                # rewrite paragraph texts
                texts = list(p.iter(W + "t"))
                if len(texts) == 1:
                    texts[0].text = new_full
                else:
                    # join into first
                    texts[0].text = new_full
                    texts[0].set(XML_SPACE, "preserve")
                    for t in texts[1:]:
                        t.text = ""
                count += 1
    return count


def insert_paragraph_after(body: ET.Element, ref_p: ET.Element, text: str) -> ET.Element:
    """Insert a simple paragraph after ref_p."""
    new_p = ET.Element(W + "p")
    r = ET.SubElement(new_p, W + "r")
    t = ET.SubElement(r, W + "t")
    t.set(XML_SPACE, "preserve")
    t.text = text
    # find parent and index
    parent = None
    for cand_parent in body.iter():
        for i, ch in enumerate(list(cand_parent)):
            if ch is ref_p:
                parent = cand_parent
                parent.insert(i + 1, new_p)
                return new_p
    body.append(new_p)
    return new_p


