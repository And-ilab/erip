def main() -> None:
    if WORK.exists():
        shutil.rmtree(WORK)
    WORK.mkdir(parents=True)

    with zipfile.ZipFile(SRC, "r") as z:
        z.extractall(WORK)
        comments = collect_comments(z)

    missing = [cid for cid in comments if cid not in RESPONSES]
    if missing:
        print("WARNING: no response for comment ids:", missing)

    write_answers_md(comments)

    doc_path = WORK / "word" / "document.xml"
    tree = ET.parse(doc_path)
    root = tree.getroot()

    n_head = apply_heading_paragraphs(root)
    n_txt = apply_text_node_replacements(root)
    update_version_strings(root)
    expand_section3(root)
    expand_section41(root)
    fill_gost_sections(root)
    expand_acceptance_and_docs(root)
    add_glossary_terms(root)
    add_enforcement_note(root)
    add_eviction_field(root)
    add_permanence_unique(root)
    fix_notar_tariff_calc(root)
    fix_manual_debt_edit(root)
    fix_writeoff_section_intro(root)

    # Second pass numbering after insertions
    apply_heading_paragraphs(root)
    apply_text_node_replacements(root)

    add_appendix3_open_questions(root)
    append_answers_table(root, comments)

    # Title note
    body = root.find(W + "body")
    if body is not None and len(body):
        note = ET.Element(W + "p")
        r = ET.SubElement(note, W + "r")
        t = ET.SubElement(r, W + "t")
        t.set(XML_SPACE, "preserve")
        t.text = (
            "Версия v1.2 от 22.07.2026: учтены комментарии Заказчика к v1.0; "
            "синхронизирована нумерация разделов с структурой ГОСТ (1–9, п. 4.2.x); "
            "ответы на замечания — в комментариях и в Приложении 4."
        )
        # insert after first few paras — find ТЕХНИЧЕСКОЕ ЗАДАНИЕ
        for p in list(body.iter(W + "p")):
            if "ТЕХНИЧЕСКОЕ ЗАДАНИЕ" in paragraph_full_text(p):
                parent = None
                for cand in body.iter():
                    for i, ch in enumerate(list(cand)):
                        if ch is p:
                            cand.insert(i + 1, note)
                            parent = cand
                            break
                    if parent is not None:
                        break
                break

    tree.write(doc_path, encoding="utf-8", xml_declaration=True)

    # Comments
    cpath = WORK / "word" / "comments.xml"
    ctree = ET.parse(cpath)
    n_c = patch_comments(ctree.getroot())
    ctree.write(cpath, encoding="utf-8", xml_declaration=True)

    # Repack
    if OUT.exists():
        OUT.unlink()
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as zout:
        for path in sorted(WORK.rglob("*")):
            if path.is_file():
                zout.write(path, path.relative_to(WORK).as_posix())

    # Verify remaining roman refs
    with zipfile.ZipFile(OUT) as z:
        doc = ET.fromstring(z.read("word/document.xml"))
    body_text = "".join((t.text or "") for t in doc.iter(W + "t"))
    left = re.findall(
        r"\b(?:XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)(?:\.\d+)+\b", body_text
    )
    # Filter false positives like "I. " in other languages — already patterned
    print("Written:", OUT)
    print("Heading renames:", n_head, "text node updates:", n_txt, "comment replies:", n_c)
    print("Remaining roman-like refs:", len(left), "unique:", sorted(set(left))[:30])
    print("Answers markdown:", ANSWERS_MD)


if __name__ == "__main__":
    main()
